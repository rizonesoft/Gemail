// Build every icon output from the canonical SVG sources in assets/icons/src/.
//
//   node tools/design/icons.mjs          render PNGs, regenerate src/ui/icons.ts, write assets/icons/manifest.json
//   node tools/design/icons.mjs --check  exit 1 when any output is missing or stale against its source
//   node tools/design/icons.mjs --sheet  also write build/icons-sheet.png, every icon at 5x and 1x, for review
//
// Sources (docs/design/icons.md is the catalog and the rules):
//   app/gemail.svg (48 box) and app/gemail-16.svg   -> assets/icons/png/app/gemail-{16,32,64,80,128,256}.png
//   ribbon/*.svg (32 box)                          -> assets/icons/png/ribbon/<name>-{16,32,80}.png
//   menu/*.svg (20 box)                            -> assets/icons/png/menu/<name>-{16,32,80}.png
//   pane/*.svg (20 box, currentColor)              -> src/ui/icons.ts (inline SVG registry, no PNGs)
//
// assets/icons/manifest.json records the sha256 of every source and output, so
// scripts/design-lint.py can prove freshness in CI without rendering.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { Resvg } from '@resvg/resvg-js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const SRC = path.join(ROOT, 'assets', 'icons', 'src');
const PNG = path.join(ROOT, 'assets', 'icons', 'png');
const REGISTRY = path.join(ROOT, 'src', 'ui', 'icons.ts');
const MANIFEST = path.join(ROOT, 'assets', 'icons', 'manifest.json');
const rel = (p) => path.relative(ROOT, p).split(path.sep).join('/');
// Line-ending-neutral: a Windows checkout holds CRLF where the index and CI hold LF.
const sha = (buf, file = '') => crypto.createHash('sha256')
  .update(file.toLowerCase().endsWith('.png') ? buf : Buffer.from(buf.toString('latin1').replace(/\r\n/g, '\n'), 'latin1'))
  .digest('hex');

const read = (p) => fs.readFileSync(p, 'utf8');
const list = (dir) => (fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith('.svg')).sort() : []);

// Each PNG job: [source file, output file, pixel size]
function jobs() {
  const out = [];
  for (const size of [32, 64, 80, 128, 256]) out.push(['app/gemail.svg', `app/gemail-${size}.png`, size]);
  out.push(['app/gemail-16.svg', 'app/gemail-16.png', 16]);
  for (const group of ['ribbon', 'menu']) {
    for (const f of list(path.join(SRC, group))) {
      for (const size of [16, 32, 80]) out.push([`${group}/${f}`, `${group}/${f.replace('.svg', '')}-${size}.png`, size]);
    }
  }
  return out;
}

function renderPng(svgText, size) {
  return new Resvg(svgText, { fitTo: { mode: 'width', value: size }, background: 'rgba(0,0,0,0)' }).render().asPng();
}

// The TypeScript registry: every pane icon as inline SVG markup, typed by name.
function registrySource() {
  const names = list(path.join(SRC, 'pane')).map((f) => f.replace('.svg', ''));
  const entries = names.map((n) => {
    const svg = read(path.join(SRC, 'pane', `${n}.svg`)).trim();
    const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
    const attrs = svg.match(/^<svg([^>]*)>/)[1].replace(/\s(xmlns|viewBox|width|height)="[^"]*"/g, '').trim();
    return `  ${JSON.stringify(n)}: { attrs: ${JSON.stringify(attrs)}, body: ${JSON.stringify(inner)} },`;
  });
  return `/**
 * Gemail icon registry -- GENERATED by tools/design/icons.mjs from assets/icons/src/pane/.
 * Do not edit by hand: change the SVG source and run \`node tools/design/icons.mjs\`.
 * Catalog and usage rules: docs/design/icons.md. scripts/design-lint.py refuses a
 * stale copy and any inline <svg> in src/ outside this file.
 */

interface IconDef {
  attrs: string;
  body: string;
}

const ICONS = {
${entries.join('\n')}
} as const satisfies Record<string, IconDef>;

export type IconName = keyof typeof ICONS;

export interface IconOptions {
  /** Rendered size in CSS pixels. Default 20 (the grid every pane icon is drawn on). */
  size?: number;
  /** Accessible name. Omit for decorative icons beside visible text (aria-hidden is set). */
  label?: string;
  /** Extra class names for the <svg> element. */
  className?: string;
}

let uid = 0;

/** Inline SVG markup for a pane icon. Filled variants are named "<icon>-filled". */
export function iconSvg(name: IconName, options: IconOptions = {}): string {
  const def: IconDef = ICONS[name];
  const size = options.size ?? 20;
  // Mask ids must be unique per instance in one document.
  const suffix = \`-gm\${(uid += 1)}\`;
  const body = def.body.replace(/id="([\\w-]+)"/g, \`id="$1\${suffix}"\`).replace(/url\\(#([\\w-]+)\\)/g, \`url(#$1\${suffix})\`);
  const a11y = options.label
    ? \`role="img" aria-label="\${options.label.replace(/"/g, "&quot;")}"\`
    : 'aria-hidden="true" focusable="false"';
  const cls = options.className ? \` class="\${options.className}"\` : "";
  return \`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 20 20" width="\${size}" height="\${size}" \${def.attrs} \${a11y}\${cls}>\${body}</svg>\`;
}

export const ICON_NAMES = Object.keys(ICONS) as IconName[];
`;
}

// Format generated TypeScript with the repository's own Prettier and config, so
// the registry passes `npm run lint` and the build and --check produce identical text.
async function formatTs(text, file) {
  const prettier = createRequire(path.join(ROOT, 'package.json'))('prettier');
  const config = (await prettier.resolveConfig(file)) || {};
  return prettier.format(text, { ...config, filepath: file });
}

async function build({ check, sheet }) {
  const manifest = { generator: 'tools/design/icons.mjs', sources: {}, outputs: {} };
  for (const group of ['app', 'ribbon', 'menu', 'pane']) {
    for (const f of list(path.join(SRC, group))) manifest.sources[`assets/icons/src/${group}/${f}`] = sha(fs.readFileSync(path.join(SRC, group, f)), f);
  }
  const problems = [];
  const outputs = {};
  for (const [src, out, size] of jobs()) outputs[`assets/icons/png/${out}`] = renderPng(read(path.join(SRC, src)), size);
  outputs[rel(REGISTRY)] = Buffer.from(await formatTs(registrySource(), REGISTRY), 'utf8');

  if (check) {
    const recorded = fs.existsSync(MANIFEST) ? JSON.parse(read(MANIFEST)) : { sources: {}, outputs: {} };
    for (const [p, h] of Object.entries(manifest.sources)) if (recorded.sources[p] !== h) problems.push(`${p} changed since the last build`);
    for (const p of Object.keys(recorded.sources)) if (!(p in manifest.sources)) problems.push(`${p} was removed since the last build`);
    for (const [p, buf] of Object.entries(outputs)) {
      const abs = path.join(ROOT, p);
      if (!fs.existsSync(abs)) { problems.push(`${p} is missing`); continue; }
      if (p.endsWith('.ts') && fs.readFileSync(abs, 'utf8').replace(/\r\n/g, '\n') !== buf.toString('utf8').replace(/\r\n/g, '\n')) problems.push(`${p} is stale`);
      if (recorded.outputs[p] !== sha(fs.readFileSync(abs), p)) problems.push(`${p} does not match the manifest`);
    }
    for (const p of Object.keys(recorded.outputs)) if (!(p in outputs)) problems.push(`${p} is recorded but no longer produced`);
    if (problems.length) {
      for (const p of problems) console.error(`icons: ${p}`);
      console.error('icons: run `node tools/design/icons.mjs` and commit the result');
      process.exit(1);
    }
    console.log(`icons: ${Object.keys(manifest.sources).length} sources, ${Object.keys(outputs).length} outputs, all current`);
  } else {
    fs.rmSync(PNG, { recursive: true, force: true });
    for (const [p, buf] of Object.entries(outputs)) {
      const abs = path.join(ROOT, p);
      fs.mkdirSync(path.dirname(abs), { recursive: true });
      fs.writeFileSync(abs, buf);
      manifest.outputs[p] = sha(buf, p);
    }
    fs.writeFileSync(MANIFEST, JSON.stringify(manifest, null, 2) + '\n');
    console.log(`icons: wrote ${Object.keys(outputs).length} outputs from ${Object.keys(manifest.sources).length} sources`);
  }
  if (sheet) writeSheet();
}

// A review sheet: every source at 5x on a pixel grid and at 1x, light and dark rows for pane icons.
function writeSheet() {
  const cells = [];
  for (const group of ['app', 'ribbon', 'menu', 'pane']) {
    for (const f of list(path.join(SRC, group))) {
      const svg = read(path.join(SRC, group, f)).trim();
      const vb = Number(svg.match(/viewBox="0 0 (\d+)/)[1]);
      cells.push({ label: `${group}/${f.replace('.svg', '')}`, vb, svg });
    }
  }
  const COLS = 8, CW = 170, CH = 150, big = 90;
  let out = `<svg xmlns="http://www.w3.org/2000/svg" width="${COLS * CW}" height="${Math.ceil(cells.length / COLS) * CH}" font-family="Segoe UI, sans-serif"><rect width="100%" height="100%" fill="#fff"/>`;
  cells.forEach((c, n) => {
    const x = (n % COLS) * CW, y = Math.floor(n / COLS) * CH;
    const s = big / c.vb;
    const inner = c.svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '').replace(/currentColor/g, '#424852').replace(/id="([\w-]+)"/g, `id="$1-${n}"`).replace(/url\(#([\w-]+)\)/g, `url(#$1-${n})`);
    const attrs = c.svg.match(/^<svg([^>]*)>/)[1].replace(/\s(xmlns|viewBox|width|height)="[^"]*"/g, '').replace(/currentColor/g, '#424852');
    out += `<rect x="${x + 8}" y="${y + 8}" width="${big + 12}" height="${big + 12}" rx="6" fill="#f3f5f8"/>`;
    out += `<g transform="translate(${x + 14},${y + 14}) scale(${s})" ${attrs}>${inner}</g>`;
    const one = c.vb === 48 ? 32 : c.vb, s1 = one / c.vb;
    out += `<g transform="translate(${x + 118},${y + 40}) scale(${s1})" ${attrs}>${inner.replace(/id="([\w-]+)"/g, 'id="$1-1x"').replace(/url\(#([\w-]+)\)/g, 'url(#$1-1x)')}</g>`;
    out += `<text x="${x + 8}" y="${y + 132}" font-size="11" fill="#1b1d22">${c.label}</text>`;
  });
  out += '</svg>';
  const file = path.join(ROOT, 'build', 'icons-sheet.png');
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, new Resvg(out, { font: { loadSystemFonts: true } }).render().asPng());
  console.log(`icons: review sheet at ${rel(file)}`);
}

await build({ check: process.argv.includes('--check'), sheet: process.argv.includes('--sheet') });
